#!/usr/bin/env python3
"""Regenerates docs/CODE_INDEX.md: every top-level function/const per source file with its line number.
Run: python3 tools/code_index.py   (re-run after big edits; it only reads the sources)"""
import re,sys,os
os.chdir(os.path.join(os.path.dirname(__file__),'..'))
FILES=['want3.html','tempo/index.html','sync_api.js','tempo_api.js','extract.js','tempo/sw.js','build_worker.py','serve.mjs']
pat=re.compile(r'^\s{0,1}(?:async\s+)?function\*?\s+([A-Za-z_$][\w$]*)|^\s{0,1}(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>|^def\s+(\w+)')
out=['# Code index','','Generated by `python3 tools/code_index.py`. Line numbers drift; regenerate after big edits.','Use it to jump straight to a function (`grep -n "name(" file`) instead of scanning whole files.','']
for f in FILES:
    if not os.path.exists(f):continue
    lines=open(f,encoding='utf8').read().split('\n')
    items=[]
    for i,l in enumerate(lines,1):
        m=pat.match(l)
        if m:items.append((i,next(g for g in m.groups() if g)))
    out+= [f'## {f} ({len(lines)} lines, {len(items)} symbols)','']
    out.append(', '.join(f'`{n}`:{i}' for i,n in items) or '_none_');out.append('')
open('docs/CODE_INDEX.md','w',encoding='utf8').write('\n'.join(out))
print('docs/CODE_INDEX.md written')
